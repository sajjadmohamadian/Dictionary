let fixedDirectCount = 0;
let fixedCompoundCount = 0;
let fixedSpaceCount = 0;

for (let i = 0; i < entries.length; i++) {
  const e = entries[i];
  const oldAz = e.az_word.trim();

  // A. Check DIRECT_CORRECTIONS
  if (DIRECT_CORRECTIONS[oldAz]) {
    const fix = DIRECT_CORRECTIONS[oldAz];
    e.az_word = fix.az;
    e.az_latin = fix.lat;
    e.fa_word = fix.fa;
    if (fix.faAlts) {
      e.fa_alternative_equivalents = fix.faAlts;
    }
    e.az_pronunciation = `${fix.az} [${fix.lat}]`;
    e.ipa = `/${fix.lat}/`;
    e.az_definition = `آذربایجان تورکجه‌سینده اصیل و تانینمیش ترکیب: «${fix.az}».`;
    e.fa_definition = `${fix.fa}. (${fix.note || 'از واژگان و اصطلاحات اصیل ترکی آذربایجانی در ایران'})`;
    fixedDirectCount++;
    continue;
  }

  // B. Check entry-compound where az_latin contained Arabic script prefix
  if (e.id.startsWith('entry-compound-')) {
    const parts = e.az_word.split(' ');
    if (parts.length === 2) {
      const p = parts[0];
      const b = parts[1];
      if (PREFIX_MAP[p] && BASE_MAP[b]) {
        const pInfo = PREFIX_MAP[p];
        const bInfo = BASE_MAP[b];
        const lat = `${pInfo.lat} ${bInfo.lat}`;
        const naturalFa = `${bInfo.fa} ${pInfo.fa}`;

        e.az_latin = lat;
        e.fa_word = naturalFa;
        e.fa_alternative_equivalents = [naturalFa, `${e.az_word} (${naturalFa})`];
        e.az_pronunciation = `${e.az_word} [${lat}]`;
        e.ipa = `/${lat}/`;
        e.fa_definition = `ترکیب نام‌واژه توصیفی و جغرافیایی در زبان و بوم آذربایجان ایران: ${naturalFa}.`;
        fixedCompoundCount++;
        continue;
      }
    }
  }

  // C. Naturalize artificial zero-width non-joiner compounds in Azerbaijani entries
  // e.g. گئجه‌نین‌سسی -> گئجه‌نین سسی
  if (e.az_word.includes('‌') && (e.id.startsWith('entry-push-') || e.id.startsWith('entry-ext2-') || e.id.startsWith('entry-fin-'))) {
    // If it's a possessive phrase with نین/ین/لرین: replace '‌' with regular space
    if (e.az_word.includes('نین‌') || e.az_word.includes('لرین‌') || e.az_word.includes('ین‌')) {
      const naturalized = e.az_word.replace(/‌/g, ' ');
      e.az_word = naturalized;
      e.az_pronunciation = `${naturalized} [${e.az_latin}]`;
      fixedSpaceCount++;
    }
  }
}

